export function getPostBySlugEs(slug) {
  return learningCenterPostsEs.find((post) => post.slug === slug);
}

export function getPostByEnglishSlugEs(enSlug) {
  return learningCenterPostsEs.find((post) => post.enSlug === enSlug);
}

export function getPostsByCategoryEs(category) {
  return learningCenterPostsEs.filter((post) => post.category === category);
}

export function getRelatedPostsEs(post, limit = 3) {
  const selected = post.relatedSlugs
    .map((slug) => getPostBySlugEs(slug))
    .filter(Boolean);

  if (selected.length >= limit) {
    return selected.slice(0, limit);
  }

  const extras = learningCenterPostsEs.filter(
    (candidate) =>
      candidate.slug !== post.slug &&
      !selected.some((item) => item.slug === candidate.slug),
  );

  return [...selected, ...extras].slice(0, limit);
}
