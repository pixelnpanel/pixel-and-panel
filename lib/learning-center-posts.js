export function getPostBySlug(slug) {
  return learningCenterPosts.find((post) => post.slug === slug);
}

export function getPostsByCategory(category) {
  return learningCenterPosts.filter((post) => post.category === category);
}

export function getRelatedPosts(post, limit = 3) {
  const selected = post.relatedSlugs
    .map((slug) => getPostBySlug(slug))
    .filter(Boolean);

  if (selected.length >= limit) {
    return selected.slice(0, limit);
  }

  const extras = learningCenterPosts.filter(
    (candidate) =>
      candidate.slug !== post.slug &&
      !selected.some((item) => item.slug === candidate.slug),
  );

  return [...selected, ...extras].slice(0, limit);
}
